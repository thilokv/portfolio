/**
 * Applies database migrations as the schema owner, then (re)applies the
 * least-privilege grants for the runtime application role.
 */
import type { Client } from "pg";
import { drizzle } from "drizzle-orm/node-postgres";
import { migrate } from "drizzle-orm/node-postgres/migrator";

export async function applyMigrationsAndGrants(client: Client, appRole: string): Promise<void> {
  if (!/^[a-z_][a-z0-9_]*$/.test(appRole)) throw new Error("Invalid application role name");
  await migrate(drizzle(client), { migrationsFolder: "./drizzle" });
  // Runtime role: data access only. No DDL, no ownership, no BYPASSRLS.
  await client.query(`
    GRANT USAGE ON SCHEMA public TO ${appRole};
    REVOKE ALL ON ALL TABLES IN SCHEMA public FROM ${appRole};
    GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA public TO ${appRole};
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO ${appRole};
    -- audit log is append-only
    REVOKE UPDATE ON audit_logs FROM ${appRole};
    -- the only tables where rows may be removed by the application
    GRANT DELETE ON auth_sessions, rate_limit_events, session_goals, goal_observations, assessment_domains, staff_roles,
                    staff_availability, password_reset_tokens TO ${appRole};
    -- the drizzle bookkeeping schema is not needed at runtime
    REVOKE ALL ON SCHEMA drizzle FROM ${appRole};
    -- Hosted Postgres (e.g. Supabase) may expose the public schema through an
    -- HTTP API with these roles. CareOS data is only reached through the app.
    DO $$
    DECLARE r text;
    BEGIN
      FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
          EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA public FROM %I', r);
          EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM %I', r);
          EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM %I', r);
        END IF;
      END LOOP;
    END $$;
  `);
}

/**
 * Creates the restricted runtime role if needed and (re)sets its password and
 * attributes. Used by hosted deployments, where no administrator creates the
 * role by hand. The password is generated by the caller (never logged).
 */
export async function ensureAppRole(client: Client, appRole: string, password: string): Promise<void> {
  if (!/^[a-z_][a-z0-9_]*$/.test(appRole)) throw new Error("Invalid application role name");
  const me = (await client.query<{ u: string }>("SELECT current_user AS u")).rows[0].u;
  if (me === appRole) throw new Error("The application role must not be the database owner");
  const { rows } = await client.query<{ exists: boolean }>("SELECT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = $1) AS exists", [appRole]);
  const literal = (await client.query<{ q: string }>("SELECT quote_literal($1) AS q", [password])).rows[0].q;
  // New roles default to NOSUPERUSER, NOBYPASSRLS, NOCREATEDB and NOCREATEROLE.
  // (Naming those attributes explicitly needs superuser rights on some hosts.)
  await client.query(`${rows[0].exists ? "ALTER" : "CREATE"} ROLE ${appRole} WITH LOGIN PASSWORD ${literal}`);
}

/**
 * Refuses to continue if the runtime role could bypass Row Level Security:
 * it must not be a superuser, have BYPASSRLS, create roles/databases, or own
 * any CareOS table (owners bypass RLS).
 */
export async function assertRestrictedRole(client: Client, appRole: string): Promise<void> {
  const { rows } = await client.query<{ rolsuper: boolean; rolbypassrls: boolean; rolcreaterole: boolean; rolcreatedb: boolean; owned: number }>(
    `SELECT r.rolsuper, r.rolbypassrls, r.rolcreaterole, r.rolcreatedb,
            (SELECT count(*)::int FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE n.nspname = 'public' AND c.relowner = r.oid) AS owned
       FROM pg_roles r WHERE r.rolname = $1`,
    [appRole],
  );
  const r = rows[0];
  if (!r) throw new Error(`Role "${appRole}" does not exist`);
  if (r.rolsuper || r.rolbypassrls || r.rolcreaterole || r.rolcreatedb || r.owned > 0) {
    throw new Error(`Role "${appRole}" has elevated privileges or owns tables; refusing to use it for the application`);
  }
}
